// Asserts ts/shared/regionalForms.ts and internal/handlers/regional.go describe the same forms.
//
//   node scripts/check-regional-form-parity.mjs
//
// The two files are parallel by hand: the TS one drives the checklist cards and the region picker,
// the Go one resolves sprites for public profiles and the mobile API and now backs the admin
// editor. regional.go has carried a "keep the two files in sync" comment since it was written,
// which is a hope, not a mechanism. Drift here is silent and ugly: a form with a card but no
// server sprite renders blank on somebody's public profile, and a region the server rejects makes
// a save fail with no explanation.
//
// It also enforces the VARCHAR(16) bound on user_shinies.region. That column is why ! and ? are
// spelled excl and qmark, and a longer tag would be truncated on write rather than rejected.

import { readFileSync } from "node:fs";

const TS = "ts/shared/regionalForms.ts";
const GO = "internal/handlers/regional.go";
const REGION_MAX = 16;

const problems = [];
const ts = readFileSync(TS, "utf8");
const go = readFileSync(GO, "utf8");

// ------------------------------------------------- parse the generated Unown and Vivillon forms
// These are built from their own arrays rather than written as literal REGIONAL_FORMS rows, so the
// literal parser below cannot see them. They still need their shiny defaults checked: Vivillon's
// two event exclusive patterns have no released shiny, and that fact has to agree with the Go map.
// Scatterbug and Spewpa are excluded by design; they mirror Vivillon rather than owning flags.
function parseGeneratedTs() {
  const forms = new Map(); // "Species|region" -> { slug, shiny }
  const vivBlock = ts.slice(ts.indexOf("export const VIVILLON_PATTERNS"), ts.indexOf("\n];", ts.indexOf("export const VIVILLON_PATTERNS")));
  const vivRe = /\{\s*region:\s*"([^"]+)",[^}]*?spriteId:\s*(?:"([^"]+)"|(\d+))[^}]*?\}/g;
  let m;
  while ((m = vivRe.exec(vivBlock))) {
    const row = m[0];
    const label = /label:\s*"([^"]+)"/.exec(row)?.[1] ?? "";
    forms.set(`Vivillon|${m[1]}`, { slug: m[2] ?? m[3], label, shiny: !/shiny:\s*false/.test(row) });
  }
  // The 26 lettered Unown are generated by a loop over the alphabet; the other two are literals.
  // Every Unown letter's shiny is released, and the mapper hardcodes shiny: true for all of them.
  for (const c of "abcdefghijklmnopqrstuvwxyz") {
    forms.set(`Unown|unown_${c}`, { slug: c === "a" ? "201" : `201-${c}`, label: c.toUpperCase(), shiny: true });
  }
  forms.set("Unown|unown_excl", { slug: "201-exclamation", label: "!", shiny: true });
  forms.set("Unown|unown_qmark", { slug: "201-question", label: "?", shiny: true });
  return forms;
}

// The Go side files these two families under ordered formVariant tables rather than
// regionalVariantID. They carry a LABEL as well as a slug, because the shiny dex manifest
// puts the Unown glyph and the Vivillon pattern name on the card, so this parses both and
// the caller checks both. A wrong label is not a broken sprite, it is a card that says the
// wrong thing, which is harder to notice and no less wrong.
function parseGoSlugMaps() {
  const out = new Map(); // "Species|region" -> { slug, label }

  // Vivillon: 20 literal {region, label, slug} triples, in card order.
  const vivStart = go.indexOf("var vivillonVariants");
  if (vivStart >= 0) {
    const body = go.slice(vivStart, go.indexOf("\n}", vivStart));
    for (const m of body.matchAll(/\{\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)"\s*\}/g)) {
      out.set(`Vivillon|${m[1]}`, { slug: m[3], label: m[2] });
    }
  }

  // Unown: the ! and ? letters are literals, in a different shape from the lettered ones.
  const unownStart = go.indexOf("var unownVariants");
  if (unownStart >= 0) {
    const body = go.slice(unownStart, go.indexOf("\n}()", unownStart));
    for (const m of body.matchAll(/formVariant\{Region:\s*"([^"]+)",\s*Label:\s*"([^"]+)",\s*Slug:\s*"([^"]+)"\}/g)) {
      out.set(`Unown|${m[1]}`, { slug: m[3], label: m[2] });
    }
  }

  // ...and the 26 lettered ones are generated by the same alphabet loop both sides use.
  if (goGeneratesUnown()) {
    for (const c of "abcdefghijklmnopqrstuvwxyz") {
      out.set(`Unown|unown_${c}`, { slug: c === "a" ? "201" : `201-${c}`, label: c.toUpperCase() });
    }
  }
  return out;
}

// The lettered Unown tags never appear as text on either side: both build them from the
// alphabet. Assert the Go generator is still there, and still shaped the way this script
// credits it for, rather than silently vouching for 26 tags that may no longer exist.
function goGeneratesUnown() {
  return (
    /for\s+_,\s*c\s*:=\s*range\s+"abcdefghijklmnopqrstuvwxyz"/.test(go) &&
    /Region:\s*"unown_"\s*\+\s*string\(c\)/.test(go) &&
    /Label:\s*strings\.ToUpper\(string\(c\)\)/.test(go)
  );
}

// regionOrder is what the shiny dex manifest sorts a species' form cards by. A tag missing
// from it ranks 0 and sorts in among the base card instead of after it, which is a quiet
// visual bug rather than a crash, so it is worth an assertion.
function parseGoRegionOrder() {
  const start = go.indexOf("var regionOrder");
  if (start < 0) return null;
  const body = go.slice(start, go.indexOf("\n}()", start));
  const out = new Set([...body.matchAll(/"([a-z_]+)"/g)].map((m) => m[1]));
  if (/for _, v := range unownVariants/.test(body) && goGeneratesUnown()) {
    for (const c of "abcdefghijklmnopqrstuvwxyz") out.add(`unown_${c}`);
    out.add("unown_excl");
    out.add("unown_qmark");
  }
  if (/for _, v := range vivillonVariants/.test(body)) {
    for (const k of parseGoSlugMaps().keys()) {
      if (k.startsWith("Vivillon|")) out.add(k.split("|")[1]);
    }
  }
  return out;
}

// ------------------------------------------------------------------ parse the TS table
// Only the explicit literal rows here; the generated Unown and Vivillon families are handled above.
function parseTs() {
  const body = ts.slice(ts.indexOf("export const REGIONAL_FORMS"), ts.indexOf("\n};", ts.indexOf("export const REGIONAL_FORMS")));
  const forms = new Map(); // "Species|region" -> { variantId, shiny }
  const speciesRe = /"([^"]+)":\s*(\[[\s\S]*?\]|UNOWN_LETTERS[^,]*|VIVILLON_PATTERNS[^,]*),/g;
  let m;
  while ((m = speciesRe.exec(body))) {
    const [, species, block] = m;
    if (!block.startsWith("[")) continue; // generated: Unown / Vivillon / Scatterbug / Spewpa
    const rowRe = /\{\s*region:\s*"([^"]+)",\s*variantId:\s*(\d+),\s*shiny:\s*(true|false)/g;
    let r;
    while ((r = rowRe.exec(block))) {
      forms.set(`${species}|${r[1]}`, { variantId: Number(r[2]), shiny: r[3] === "true" });
    }
  }
  return forms;
}

// ------------------------------------------------------------------ parse the Go table
function parseGo() {
  const body = go.slice(go.indexOf("var regionalVariantID"), go.indexOf("\n}\n", go.indexOf("var regionalVariantID")));
  const forms = new Map();
  const lineRe = /"([^"]+)":\s*\{([^}]*)\}/g;
  let m;
  while ((m = lineRe.exec(body))) {
    const species = m[1];
    const pairRe = /"([^"]+)":\s*(\d+)/g;
    let p;
    while ((p = pairRe.exec(m[2]))) {
      forms.set(`${species}|${p[1]}`, { variantId: Number(p[2]) });
    }
  }
  return forms;
}

// The Go "not released yet" exceptions map; everything else defaults released.
function parseGoUnreleased() {
  const start = go.indexOf("var regionalShinyUnreleased");
  if (start < 0) return null;
  const body = go.slice(start, go.indexOf("\n}\n", start));
  const out = new Set();
  const lineRe = /"([^"]+)":\s*\{([^}]*)\}/g;
  let m;
  while ((m = lineRe.exec(body))) {
    const species = m[1];
    const pairRe = /"([^"]+)":\s*true/g;
    let p;
    while ((p = pairRe.exec(m[2]))) out.add(`${species}|${p[1]}`);
  }
  return out;
}

const tsForms = parseTs();
const goForms = parseGo();
const goUnreleased = parseGoUnreleased();

if (!tsForms.size) problems.push(`parsed 0 forms out of ${TS}; the parser in this script is stale.`);
if (!goForms.size) problems.push(`parsed 0 forms out of ${GO}; the parser in this script is stale.`);
if (goUnreleased === null) problems.push(`${GO} has no regionalShinyUnreleased map.`);

// 1. Same set of (species, region) pairs.
for (const key of tsForms.keys()) {
  if (!goForms.has(key)) problems.push(`${key} is in ${TS} but not in ${GO}: its sprite will not resolve server side.`);
}
for (const key of goForms.keys()) {
  if (!tsForms.has(key)) problems.push(`${key} is in ${GO} but not in ${TS}: it gets no checklist card.`);
}

// 2. Same variant ids. A mismatch means the browser and the server show different art.
for (const [key, tsRow] of tsForms) {
  const goRow = goForms.get(key);
  if (goRow && goRow.variantId !== tsRow.variantId) {
    problems.push(`${key}: variant id ${tsRow.variantId} in TS but ${goRow.variantId} in Go.`);
  }
}

// 3. Same shiny defaults. The Go map records only the unreleased pairs; the TS table records a
//    boolean per row. They have to agree, or the admin editor shows a default the page does not use.
const tsGenerated = parseGeneratedTs();
const goSlugs = parseGoSlugMaps();

if (goUnreleased) {
  // Literal rows and generated families both have to agree with the Go exceptions map.
  const allTs = new Map([...tsForms, ...tsGenerated]);
  for (const [key, tsRow] of allTs) {
    const goSaysUnreleased = goUnreleased.has(key);
    if (tsRow.shiny === goSaysUnreleased) {
      problems.push(
        `${key}: TS says shiny ${tsRow.shiny}, Go says ${goSaysUnreleased ? "not released" : "released"}.`,
      );
    }
  }
  for (const key of goUnreleased) {
    if (!allTs.has(key)) problems.push(`${key} is listed unreleased in ${GO} but is not a form in ${TS}.`);
  }
}

// The generated families resolve their art through slug maps rather than numeric variant ids, so
// a drift there shows as a broken sprite rather than a wrong flag. Check both sides agree.
for (const [key, tsRow] of tsGenerated) {
  const goRow = goSlugs.get(key);
  if (goRow === undefined) {
    problems.push(`${key} is in ${TS} but has no sprite slug in ${GO}: its art will not resolve server side.`);
    continue;
  }
  if (String(goRow.slug) !== String(tsRow.slug)) {
    problems.push(`${key}: sprite slug ${JSON.stringify(tsRow.slug)} in TS but ${JSON.stringify(goRow.slug)} in Go.`);
  }
  // The label is what the shiny dex manifest prints on the card. TS renders it from its own
  // table, Go from its copy, so a drift means the app and the website name the same form
  // differently: an Unown card reading the wrong glyph, or a Vivillon pattern the wrong name.
  if (tsRow.label && goRow.label !== tsRow.label) {
    problems.push(`${key}: card label ${JSON.stringify(tsRow.label)} in TS but ${JSON.stringify(goRow.label)} in Go.`);
  }
}
for (const key of goSlugs.keys()) {
  if (!tsGenerated.has(key)) problems.push(`${key} has a sprite slug in ${GO} but is not a form in ${TS}.`);
}

// 4. Every region is accepted by the server, and fits user_shinies.region.
const validBody = go.slice(go.indexOf("var validRegions"), go.indexOf("\n}\n", go.indexOf("var validRegions")));
const valid = new Set([...validBody.matchAll(/"([^"]*)":\s*true/g)].map((m) => m[1]));
// The Unown letters and Vivillon patterns are folded into validRegions by init(). The Vivillon
// tags are literal keys, but 26 of the 28 Unown tags are BUILT by a loop over the alphabet, so
// they never appear as text. Assert the generator exists, then credit what it produces; both
// sides generate the same 26 the same way.
// Both families are folded in by init(), which ranges over the slug maps derived from the
// ordered formVariant tables, so what those tables contain is exactly what init() credits.
for (const key of goSlugs.keys()) valid.add(key.split("|")[1]);
if (!goGeneratesUnown()) {
  problems.push(`${GO} no longer generates the 26 lettered Unown region tags; this script assumed it did.`);
} else {
  for (const c of "abcdefghijklmnopqrstuvwxyz") valid.add(`unown_${c}`);
}
const allRegions = new Set([...tsForms.keys(), ...tsGenerated.keys()].map((k) => k.split("|")[1]));
for (const m of ts.matchAll(/region:\s*`unown_\$\{c\}`|region:\s*"(unown_[a-z]+|viv_[a-z_]+)"/g)) {
  if (m[1]) allRegions.add(m[1]);
}
for (const c of "abcdefghijklmnopqrstuvwxyz") allRegions.add(`unown_${c}`);
for (const region of allRegions) {
  if (!valid.has(region)) problems.push(`region ${JSON.stringify(region)} is not in validRegions in ${GO}: a save with it is rejected.`);
  if (region.length > REGION_MAX) {
    problems.push(`region ${JSON.stringify(region)} is ${region.length} chars; user_shinies.region is VARCHAR(${REGION_MAX}).`);
  }
}

// 5. regionOrder covers every form tag. A tag missing from it ranks 0 in the shiny dex
//    manifest and sorts in among the base species card instead of after it, which is a quiet
//    visual bug: the card is present, just in the wrong place.
const goOrder = parseGoRegionOrder();
if (goOrder === null) {
  problems.push(`${GO} has no regionOrder table; the shiny dex manifest cannot sort its form cards.`);
} else {
  for (const region of allRegions) {
    if (!goOrder.has(region)) {
      problems.push(`region ${JSON.stringify(region)} is missing from regionOrder in ${GO}: its card sorts before the base species card.`);
    }
  }
  for (const region of goOrder) {
    if (!allRegions.has(region)) {
      problems.push(`region ${JSON.stringify(region)} is in regionOrder in ${GO} but is not a form in ${TS}.`);
    }
  }
}

if (problems.length) {
  console.error("FAILED: regional form tables have drifted.\n");
  for (const p of problems) console.error("  - " + p);
  console.error(`\nReconcile ${TS} and ${GO}.`);
  process.exit(1);
}

const unreleased = [...tsForms, ...tsGenerated].filter(([, v]) => !v.shiny).map(([k]) => k);
console.log(
  `regional form parity: ${tsForms.size} literal forms and ${tsGenerated.size} generated Unown/Vivillon forms ` +
  `match between ${TS} and ${GO} on region, variant id, sprite slug, card label and shiny default; ` +
  `${unreleased.length} are flagged shiny-not-released on both sides (${unreleased.join(", ")}); ` +
  `every region tag is accepted by validRegions, is ordered by regionOrder, and fits VARCHAR(${REGION_MAX}).`,
);
