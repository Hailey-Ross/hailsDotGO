// Generates internal/handlers/costumes_data.go from the costume tables in
// ts/shared/costumes.ts, so the Go public-profile handler resolves costume
// sprites the same way the client does. Run from the repo root:
//
//   node scripts/gen-costumes.mjs
//
// The SHARED_COSTUMES eligibility (dex[]) in costumes.ts is itself derived from the
// pokemon-go-api/assets file tree; to refresh it after new events, list the tree
//   curl -s "https://api.github.com/repos/pokemon-go-api/assets/git/trees/main?recursive=1"
// and collect the dex numbers of each `pm{dex}.{c|f}{CODE}.s.icon.png` you want to map.
import { build } from "esbuild";
import { writeFileSync } from "fs";
import { createRequire } from "module";
import vm from "vm";

const require = createRequire(import.meta.url);

const res = await build({
  entryPoints: ["ts/shared/costumes.ts"],
  bundle: true,
  format: "cjs",
  platform: "node",
  write: false,
});
const mod = { exports: {} };
vm.runInNewContext(res.outputFiles[0].text, { module: mod, exports: mod.exports, require });
const { COSTUME_SPRITES, SHARED_COSTUMES } = mod.exports;

const s = (v) => JSON.stringify(v); // valid Go double-quoted string literal for our data

let out = "";
out += "package handlers\n\n";
out += "// Code generated by scripts/gen-costumes.mjs; DO NOT EDIT.\n";
out += "// Source of truth: ts/shared/costumes.ts (COSTUME_SPRITES + SHARED_COSTUMES).\n\n";
out += "type costumeCode struct {\n\tp    string\n\tcode string\n}\n\n";

out += "// species name -> costume label -> {prefix, Niantic code}\n";
out += "var costumeOverrides = map[string]map[string]costumeCode{\n";
for (const [name, labels] of Object.entries(COSTUME_SPRITES)) {
  out += `\t${s(name)}: {\n`;
  for (const [label, e] of Object.entries(labels)) {
    out += `\t\t${s(label)}: {${s(e.p)}, ${s(e.code)}},\n`;
  }
  out += "\t},\n";
}
out += "}\n\n";

out += "type sharedCostume struct {\n\tlabel   string\n\tp       string\n\tcode    string\n\tdex     map[int]bool\n\tpending bool\n}\n\n";
out += "// costumes shared by one code across many species; dex is the eligible set.\n";
out += "// a pending costume has no upstream art yet and never resolves to a sprite.\n";
out += "var sharedCostumes = []sharedCostume{\n";
for (const sc of SHARED_COSTUMES) {
  const dex = sc.dex.map((d) => `${d}: true`).join(", ");
  out += `\t{${s(sc.label)}, ${s(sc.p)}, ${s(sc.code)}, map[int]bool{${dex}}, ${sc.pending === true}},\n`;
}
out += "}\n";

writeFileSync("internal/handlers/costumes_data.go", out);
console.log(
  `wrote internal/handlers/costumes_data.go: ${Object.keys(COSTUME_SPRITES).length} override species, ${SHARED_COSTUMES.length} shared costumes`,
);
